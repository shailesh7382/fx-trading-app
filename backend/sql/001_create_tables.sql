-- FX backend schema for Oracle Database 19c and later.
-- Run as the application schema owner.

CREATE TABLE BKND_FX_USER (
    USERNAME             VARCHAR2(255 CHAR) NOT NULL,
    PASSWORD             VARCHAR2(255 CHAR),
    USER_TYPE            NUMBER(3, 0),
    LAST_LOGIN_TIMESTAMP TIMESTAMP(6),
    EMAIL                VARCHAR2(255 CHAR),
    REGION               NUMBER(3, 0),
    CONSTRAINT BKND_FX_USER_PK PRIMARY KEY (USERNAME),
    CONSTRAINT BKND_FX_USER_TYPE_CK CHECK (USER_TYPE IS NULL OR USER_TYPE BETWEEN 0 AND 5),
    CONSTRAINT BKND_FX_USER_REGION_CK CHECK (REGION IS NULL OR REGION BETWEEN 0 AND 2)
);

CREATE TABLE BKND_LIMIT_ORDER (
    ID                   VARCHAR2(255 CHAR) NOT NULL,
    REQUEST_ID           VARCHAR2(255 CHAR),
    ORIGINAL_REQUEST_ID  VARCHAR2(255 CHAR),
    RESPONSE_ID          VARCHAR2(255 CHAR),
    RESPONSE_AT          TIMESTAMP(6) WITH TIME ZONE,
    CHANNEL              VARCHAR2(255 CHAR),
    SEGMENT              VARCHAR2(255 CHAR),
    CUSTOMER_ID          VARCHAR2(255 CHAR),
    CCY_PAIR             VARCHAR2(255 CHAR),
    TENOR                VARCHAR2(255 CHAR),
    QTY                  FLOAT(53) NOT NULL,
    DIRECTION            VARCHAR2(255 CHAR),
    DEALT_CURRENCY       VARCHAR2(255 CHAR),
    QUANTITY_CURRENCY    VARCHAR2(255 CHAR),
    CONTRACT_TENOR       VARCHAR2(255 CHAR),
    LIMIT_PRICE          FLOAT(53) NOT NULL,
    TIME_IN_FORCE        VARCHAR2(255 CHAR),
    GOOD_TILL_DATE       DATE,
    TRADE_DATE           DATE,
    SETTLEMENT_DATE      DATE,
    CUSTOMER             VARCHAR2(255 CHAR),
    RM                   VARCHAR2(255 CHAR),
    SALES                VARCHAR2(255 CHAR),
    COMMENTS             VARCHAR2(1024 CHAR),
    TRADER               VARCHAR2(255 CHAR),
    STATUS               VARCHAR2(255 CHAR),
    SUBMITTED_AT         TIMESTAMP(6),
    EXECUTED_AT          TIMESTAMP(6),
    EXECUTED_PRICE       FLOAT(53),
    EXPIRES_AT           TIMESTAMP(6) WITH TIME ZONE,
    LAST_EVALUATED_AT    TIMESTAMP(6) WITH TIME ZONE,
    LAST_EVALUATED_PRICE FLOAT(53),
    CLOSED_AT            TIMESTAMP(6) WITH TIME ZONE,
    TRADING_SYSTEM_TRADE_ID VARCHAR2(255 CHAR),
    CALLBACK_URL         VARCHAR2(255 CHAR),
    CALLBACK_STATUS      VARCHAR2(255 CHAR),
    CALLBACK_ATTEMPTS    NUMBER(10, 0),
    LAST_EVENT_ID        VARCHAR2(255 CHAR),
    EVENT_RECEIVED_AT    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT BKND_LIMIT_ORDER_PK PRIMARY KEY (ID),
    CONSTRAINT BKND_LIMIT_TIF_CK CHECK (TIME_IN_FORCE IS NULL OR TIME_IN_FORCE IN ('GTC', 'GTD')),
    CONSTRAINT BKND_LIMIT_STATUS_CK CHECK (
        STATUS IS NULL OR STATUS IN ('ACTIVE', 'EXECUTED', 'EXPIRED', 'CANCELLED')
    )
);

CREATE TABLE BKND_TRADE (
    ID                   VARCHAR2(255 CHAR) NOT NULL,
    QUOTE_ID             VARCHAR2(255 CHAR),
    REQUEST_ID           VARCHAR2(255 CHAR),
    ORIGINAL_REQUEST_ID  VARCHAR2(255 CHAR),
    RESPONSE_ID          VARCHAR2(255 CHAR),
    RESPONSE_AT          TIMESTAMP(6) WITH TIME ZONE,
    CHANNEL              VARCHAR2(255 CHAR),
    SEGMENT              VARCHAR2(255 CHAR),
    CUSTOMER_ID          VARCHAR2(255 CHAR),
    CCY_PAIR             VARCHAR2(255 CHAR),
    TENOR                VARCHAR2(255 CHAR),
    QTY                  FLOAT(53) NOT NULL,
    DIRECTION            VARCHAR2(255 CHAR),
    DEALT_CURRENCY       VARCHAR2(255 CHAR),
    QUANTITY_CURRENCY    VARCHAR2(255 CHAR),
    PRICE                FLOAT(53) NOT NULL,
    COVER_PRICE          FLOAT(53),
    SWAP_POINTS          FLOAT(53),
    BUY_CURRENCY         VARCHAR2(255 CHAR),
    BUY_QUANTITY         FLOAT(53),
    SELL_CURRENCY        VARCHAR2(255 CHAR),
    SELL_QUANTITY        FLOAT(53),
    SPOT_DATE            DATE,
    VALUE_DATE           DATE,
    CUSTOMER             VARCHAR2(255 CHAR),
    RM                   VARCHAR2(255 CHAR),
    SALES                VARCHAR2(255 CHAR),
    TRADE_DATE           DATE,
    SETTLEMENT_DATE      DATE,
    COMMENTS             VARCHAR2(1024 CHAR),
    TRADER               VARCHAR2(255 CHAR),
    STATUS               VARCHAR2(255 CHAR),
    BOOKING_MODE         VARCHAR2(255 CHAR),
    EXECUTION_TYPE       VARCHAR2(255 CHAR),
    LIMIT_ORDER_ID       VARCHAR2(255 CHAR),
    PRODUCT_TYPE         VARCHAR2(255 CHAR),
    PRODUCT_DETAILS      VARCHAR2(1024 CHAR),
    MARKET_SOURCE        VARCHAR2(255 CHAR),
    BOOKED_AT            TIMESTAMP(6),
    CONSTRAINT BKND_TRADE_PK PRIMARY KEY (ID),
    CONSTRAINT BKND_TRADE_LIMIT_ORDER_FK FOREIGN KEY (LIMIT_ORDER_ID)
        REFERENCES BKND_LIMIT_ORDER (ID)
);

CREATE TABLE BKND_ID_BLOCK_ALLOCATION (
    SEQUENCE_NAME VARCHAR2(64 CHAR) NOT NULL,
    NEXT_VALUE    NUMBER(19, 0) NOT NULL,
    CONSTRAINT BKND_ID_BLOCK_ALLOC_PK PRIMARY KEY (SEQUENCE_NAME),
    CONSTRAINT BKND_ID_BLOCK_VALUE_CK CHECK (NEXT_VALUE >= 0)
);
